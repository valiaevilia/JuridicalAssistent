def draft_for(chunks, *, texts=None, status="answered", missing=None):
    texts = texts or [c.text for c in chunks]
    return {"status": status, "answer": " ".join(texts),
            "claims": [{"text": text, "chunk": f"Д{i+1}", "quote": c.text}
                       for i, (c, text) in enumerate(zip(chunks, texts))],
            "missing": missing or [], "assumptions": [], "calc": []}
